"""Phase 5: the same pipeline on the real IBM AML benchmark.

Reads reports/ibm/*.json (written by the unchanged Phase 1-3 scripts under
ARENA_CONFIG=config/ibm.yaml, plus prepare_ibm.py and phase5_transfer.py) next
to the synthetic reports/, so every comparison on this page is like for like.
"""

from __future__ import annotations

import numpy as np
import pandas as pd
import plotly.graph_objects as go
import streamlit as st

from dashboard import data

SYN, IBM = "#718096", "#2b6cb0"


def render() -> None:
    st.title("🌍 Phase 5 — Real Data: the IBM AML Benchmark")
    st.caption(
        "The unchanged Phase 1-3 pipeline on IBM's HI-Small dataset (5.08M transactions, "
        "370 labelled laundering attempts). Objective 1 names this dataset."
    )
    prof = data.ibm("phase5_data")
    p1 = data.ibm("phase1_metrics")
    if prof is None or p1 is None:
        st.warning(
            "No IBM results yet. Put HI-Small_Trans.csv and HI-Small_Patterns.txt in data/raw/, then:\n\n"
            "```bash\nARENA_CONFIG=config/ibm.yaml uv run python scripts/prepare_ibm.py\n"
            "ARENA_CONFIG=config/ibm.yaml uv run python scripts/train_detector.py\n"
            "ARENA_CONFIG=config/ibm.yaml uv run python scripts/evolve_adversary.py\n"
            "ARENA_CONFIG=config/ibm.yaml uv run python scripts/run_arena.py\n"
            "uv run python scripts/phase5_transfer.py\n```"
        )
        return
    st.info(
        "**What this data is.** IBM's AML set is the standard public benchmark for transaction-level "
        "anti-money-laundering, generated by IBM's AMLworld simulator (real labelled bank data cannot "
        "be published). It was built independently of this project, so it is a fair test of whether "
        "anything learned on our own synthetic world holds up."
    )
    _data(prof)
    st.divider()
    _detector(p1)
    st.divider()
    _transfer()
    st.divider()
    _adversary()
    st.divider()
    _arms_race()


def _data(prof: dict) -> None:
    st.header("1. Cleaning, found by profiling first")
    c, p = prof["cleaning"], prof["profile"]
    a, b, cc, d = st.columns(4)
    a.metric("Transactions kept", f"{p['rows']:,}", delta=f"-{c['rows_read'] - p['rows']:,} of {c['rows_read']:,}",
             delta_color="off")
    b.metric("Laundering", f"{p['positives']:,}", delta=f"{p['positive_rate']:.3%} of rows", delta_color="off")
    cc.metric("Accounts", f"{p['accounts']:,}")
    d.metric("Live days", p["days"])
    st.table(pd.DataFrame([
        {"step": "Self-transfers dropped", "rows": f"{c['self_transfers_dropped']:,}",
         "laundering among them": f"{c['self_transfer_positives_dropped']:,}",
         "why": "a transfer with no counterparty is not something an adversary can hide behind"},
        {"step": f"Dead tail cut (from {c['tail_cut_at'][:10]})", "rows": f"{c['tail_rows_dropped']:,}",
         "laundering among them": f"{c['tail_positives_dropped']:,}",
         "why": "background traffic stops but laundering continues; left in, 'late = laundering' would leak"},
        {"step": "Positives not in the patterns file", "rows": f"{p['typology_rows'].get('unattributed', 0):,}",
         "laundering among them": "all", "why": "labelled 'unattributed', not folded into a typology"},
    ]))
    r = p["round_100_share"]
    st.markdown(
        f"The synthetic world's best-known artefact is **absent** here: round $100 amounts are "
        f"{r['benign']:.3%} of benign and {r['laundering']:.3%} of laundering (synthetic: 21.6% and 0%). "
        f"A different shortcut takes its place: **{p['payment_format_share']['laundering'].get('ACH', 0):.0%} "
        f"of IBM laundering is paid by ACH**, against "
        f"{p['payment_format_share']['benign'].get('ACH', 0):.0%} of benign traffic."
    )


def _detector(p1: dict) -> None:
    st.header("2. The detector on real data")
    syn = data.phase1_metrics()
    h = p1["holdout"]
    cols = st.columns(3)
    s = syn["holdout"] if syn else None
    cols[0].metric("Recall @ 0.5% budget", f"{h['recall_at_budget']:.3f}",
                   delta=f"{h['recall_at_budget'] - s['recall_at_budget']:+.3f} vs synthetic" if s else None)
    cols[1].metric("PR-AUC", f"{h['pr_auc']:.3f}",
                   delta=f"{h['pr_auc'] - s['pr_auc']:+.3f} vs synthetic" if s else None)
    cols[2].metric("Precision @ budget", f"{h['precision_at_budget']:.3f}")
    typ = h["typology_recall"]
    names = [t for t in ("fan-out", "fan-in", "cycle", "gather-scatter", "stack", "unattributed") if t in typ]
    fig = go.Figure()
    if s:
        fig.add_bar(name="synthetic", x=names, y=[s["typology_recall"].get(t) for t in names], marker_color=SYN)
    fig.add_bar(name="IBM HI-Small", x=names, y=[typ[t] for t in names], marker_color=IBM)
    fig.update_layout(barmode="group", height=330, yaxis=dict(range=[0, 1], title="recall @ budget"),
                      margin=dict(l=10, r=10, t=10, b=10), legend=dict(orientation="h", y=1.1))
    st.plotly_chart(fig, width="stretch")
    st.caption(
        "The patterned typologies are caught at 0.86-0.96; the positives the patterns file does not list, "
        "at 0.26. The headline recall averages two very different populations."
    )


def _transfer() -> None:
    st.header("3. Nothing transfers between the two worlds")
    t = data.ibm("phase5_transfer")
    if t is None:
        st.info("Run `scripts/phase5_transfer.py` for the transfer matrix and ablations.")
        return
    names = ["synthetic", "ibm"]
    M = np.array([[t["transfer"][f"{d}->{s}"]["recall_at_budget"] for s in names] for d in names])
    c1, c2 = st.columns([1, 1.4])
    fig = go.Figure(go.Heatmap(z=M, x=["scored on synthetic", "scored on IBM"],
                               y=["trained on synthetic", "trained on IBM"], zmin=0, zmax=1,
                               colorscale="RdYlGn", text=np.round(M, 3), texttemplate="%{text}",
                               hovertemplate="%{y}, %{x}: recall %{z:.3f}<extra></extra>"))
    fig.update_layout(height=320, margin=dict(l=10, r=10, t=10, b=10), yaxis=dict(autorange="reversed"))
    c1.plotly_chart(fig, width="stretch")
    groups = list(t["ablation"]["ibm"])
    bar = go.Figure()
    for n, colour in (("synthetic", SYN), ("ibm", IBM)):
        bar.add_bar(name=n, x=groups, y=[t["ablation"][n][g]["recall_at_budget"] for g in groups],
                    marker_color=colour)
    bar.update_layout(barmode="group", height=320, yaxis=dict(range=[0, 1], title="recall @ budget"),
                      margin=dict(l=10, r=10, t=10, b=10), legend=dict(orientation="h", y=1.12))
    c2.plotly_chart(bar, width="stretch")
    st.markdown(
        "- **Cross-dataset:** each detector catches essentially none of the other world's laundering "
        "(chance at this budget is ≈0.005). Synthetic numbers are a pipeline check, not a result.\n"
        "- **PaySim stand-in:** PaySim has no comparable account graph, so only the 17 per-transaction "
        "features would carry over. Retrained on those alone, recall falls to under a third on both "
        "datasets: a PaySim validation would have measured mostly the part of the detector that does not matter."
    )


def _adversary() -> None:
    st.header("4. The adversary against the IBM detector")
    p2 = data.ibm("phase2_metrics")
    if p2 is None:
        st.info("Run the IBM `evolve_adversary.py` for this section.")
        return
    h = p2["headline"]
    c = st.columns(3)
    c[0].metric("Detector recall — naive strategy", f"{h['detector_recall_naive']:.1%}")
    c[1].metric("Detector recall — random strategies", f"{h['detector_recall_random']:.1%}")
    c[2].metric("Detector recall — evolved strategy", f"{h['detector_recall_evolved']:.1%}")
    st.markdown(
        "On IBM data even the *hand-written* strategy goes almost unflagged. Re-scoring its transfers with "
        "**only the payment format changed to ACH** lifts the detector's median score from 0.0006 to 0.62. "
        "The IBM-trained detector largely learned that *laundering is ACH*, because 88% of the labelled "
        "laundering is. A launderer who pays by cheque is close to invisible to it — the project's thesis, "
        "shown on the real benchmark: validation on a static dataset measures that dataset's signature."
    )
    with st.expander("The first IBM adversary run was invalid, and why"):
        st.markdown(
            "It reported evasion 1.000 and a **completion of 525× the goal**. Reading the decoded "
            "transactions showed three holes in the simulation, not a strategy:\n\n"
            "1. IBM amounts are in each row's own currency, so chaining USD→Yen legs *created money*, "
            "breaking invariant 2.\n"
            "2. The decoder paid one account's tranches in five currencies within minutes; 98% of IBM "
            "accounts use one currency.\n"
            "3. It used *Reinvestment* between two accounts, a format that occurs in IBM only as a "
            "self-transfer, so the detector had never seen it.\n\n"
            "Fix (`RealWorld` in the decoder): on real data an operation stays in one currency and uses "
            "only accounts and payment formats the ledger itself uses. A regression test decodes 300 random "
            "genomes on the real-data path and checks money is conserved."
        )


def _arms_race() -> None:
    st.header("5. The arms race on IBM")
    p3 = data.ibm("phase3_metrics")
    if p3 is None:
        st.info("The IBM closed loop has not finished yet (`run_arena.py` under the IBM overlay).")
        return
    syn = data.phase3_metrics()
    fig = go.Figure()
    for res, name, colour in ((syn, "synthetic", SYN), (p3, "IBM HI-Small", IBM)):
        if res is None:
            continue
        own = [a["champion_vs_own"] for a in res["adversaries"]]
        r = [a["round"] for a in res["adversaries"]]
        fig.add_scatter(x=r, y=[o["detector_recall"] for o in own], mode="lines+markers",
                        name=f"{name}: detector recall vs its adversary", line=dict(color=colour, width=3))
        fig.add_scatter(x=r, y=[o["success_rate"] for o in own], mode="lines+markers",
                        name=f"{name}: adversary success", line=dict(color=colour, dash="dot"))
    fig.update_layout(height=380, yaxis=dict(range=[0, 1.05]), xaxis=dict(title="round r", dtick=1),
                      margin=dict(l=10, r=10, t=10, b=10), legend=dict(orientation="h", y=1.15))
    st.plotly_chart(fig, width="stretch")
    dets = p3["detectors"]
    c = st.columns(2)
    c[0].metric("IBM holdout recall @ budget, D_0 → D_R",
                f"{dets[-1]['holdout']['recall_at_budget']:.3f}",
                delta=f"{dets[-1]['holdout']['recall_at_budget'] - dets[0]['holdout']['recall_at_budget']:+.3f}")
    c[1].metric("IBM holdout PR-AUC, D_0 → D_R", f"{dets[-1]['holdout']['pr_auc']:.3f}",
                delta=f"{dets[-1]['holdout']['pr_auc'] - dets[0]['holdout']['pr_auc']:+.3f}")
    M = np.array(p3["crossplay"]["recall"])
    hm = go.Figure(go.Heatmap(z=M, x=[f"A_{j}" for j in range(M.shape[1])], y=[f"D_{i}" for i in range(M.shape[0])],
                              zmin=0, zmax=1, colorscale="RdYlGn", text=np.round(M, 2), texttemplate="%{text}"))
    hm.update_layout(height=360, margin=dict(l=10, r=10, t=30, b=10), yaxis=dict(autorange="reversed"),
                     title=dict(text="Cross-play on IBM: detector recall, every detector vs every adversary",
                                font=dict(size=13)))
    st.plotly_chart(hm, width="stretch")
